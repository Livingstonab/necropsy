"""The revival-spec builder, shared by the web button and the MCP tool (R-12, E8).

NECROPSY's whole Kiro story is this document: a post-mortem turned into a spec a
Kiro session can act on. It is built once, here, so the "Resurrect in Kiro"
button and the `write_revival_spec` MCP tool produce the same bytes — two
surfaces over one builder (E8).

The spec is a transform of the analysis, never an invention. Every task maps to a
resurrection-plan step the pipeline already produced, and every step names the
factor it addresses, which is a factor with a non-zero contribution (R-10.2). The
cause of death and its evidence are carried through verbatim so Kiro has the
"why" as context, not just the "what". Nothing here calls a model or the network.
"""

from __future__ import annotations

from typing import Any


def build_revival_spec(analysis: Any) -> str:
    """Render the analysis as a Kiro-ready revival spec in Markdown.

    The output contains, in order: the epitaph, the cause of death with its
    evidence, the full factor scorecard as a table, and the three plan steps
    expanded into checklist tasks, each naming the factor it addresses (R-12.2).
    """
    facts = analysis.facts
    card = analysis.scorecard
    narrative = analysis.narrative
    repo = f"{facts.owner}/{facts.name}"

    lines: list[str] = []
    lines.append(f"# Revival spec — {repo}")
    lines.append("")
    lines.append(f"> {narrative.epitaph.text}")
    lines.append("")
    lines.append(
        f"_Generated by NECROPSY from GitHub metadata as of {facts.as_of.date()}. "
        f"Revival difficulty {card.score}/100 ({card.band.label}). "
        f"Epitaph source: {narrative.epitaph.source}._"
    )
    lines.append("")

    # -- context: why it died ----------------------------------------------
    lines.append("## Cause of death")
    lines.append("")
    lines.append(f"**{narrative.cause_of_death.headline}**")
    lines.append("")
    lines.append(narrative.cause_of_death.narrative)
    lines.append("")
    if narrative.cause_of_death.evidence:
        lines.append("Evidence:")
        lines.append("")
        for ev in narrative.cause_of_death.evidence:
            lines.append(f"- `{ev.fact_key}` = `{ev.fact_value}` — {ev.claim}")
        lines.append("")

    # -- the auditable scorecard -------------------------------------------
    lines.append("## Revival difficulty scorecard")
    lines.append("")
    lines.append("| Factor | Normalized | Weight | Contribution | Confidence |")
    lines.append("|---|---:|---:|---:|---|")
    for factor in card.factors:
        lines.append(
            f"| {factor.label} | {factor.normalized:.2f} | {factor.weight} | "
            f"{factor.contribution:.1f} | {factor.confidence} |"
        )
    lines.append(f"| **Total** | | | **{card.total_unrounded:.1f}** | |")
    lines.append("")
    if card.data_gaps:
        lines.append(f"_Data gaps (neutral defaults used): {', '.join(card.data_gaps)}._")
        lines.append("")
    lines.append(f"_Weights checksum: {card.weights_checksum}._")
    lines.append("")

    # -- the tasks ---------------------------------------------------------
    lines.append("## Resurrection plan")
    lines.append("")
    lines.append(
        f"_Plan source: {narrative.resurrection_plan_source}. Order tasks by "
        f"dependency; do not delete a file the analysis does not confirm is "
        f"unreferenced._"
    )
    lines.append("")
    for step in narrative.resurrection_plan:
        lines.append(f"### Task {step.order}: {step.title}")
        lines.append("")
        lines.append(f"- [ ] {step.detail}")
        lines.append(f"  - **Addresses factor:** `{step.addresses_factor}`")
        lines.append(f"  - **Estimated effort:** {step.estimated_effort}")
        contribution = _contribution_for(card, step.addresses_factor)
        if contribution is not None:
            lines.append(
                f"  - **Acceptance:** the `{step.addresses_factor}` factor "
                f"(currently contributing {contribution:.1f} points) is reduced."
            )
        lines.append("")

    lines.append("---")
    lines.append(
        "_NECROPSY reads GitHub metadata only; it never cloned or executed this "
        "repository. Verify each step against the live repository before acting._"
    )
    lines.append("")
    return "\n".join(lines)


def _contribution_for(card: Any, factor_key: str) -> float | None:
    factor = card.factor(factor_key)
    return factor.contribution if factor is not None else None
